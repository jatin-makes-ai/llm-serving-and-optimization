QUESTIONS = [
    "What is the exact nominal oxidizer-to-fuel mixture ratio for the Service Propulsion System?",
    "What is the internal master clock oscillator frequency of the Apollo Guidance Computer?",
    "What is the storage pressure and temperature of the liquid oxygen (LOX) cryogenic tanks?",
    "What is the vacuum specific impulse (Isp) of the Service Propulsion System engine?",
    "What is the coherent downlink carrier frequency of the unified S-band subsystem?",
    "How many degrees of freedom does the inertial measurement unit (IMU) gimbaled platform have?",
    "What is the storage pressure of the high-pressure titanium helium bottle?",
    "What is the ampere-hour capacity of each silver-zinc secondary battery used for reentry?",
    "What is the maximum thickness of the ablative heat shield at the aft toroidal rim?",
    "What is the maximum dynamic pressure limit for drogue parachute deployment?"
]

def run_benchmark(tag=""):
    print(f"\n=========================================================================")
    print(f"   PREFIX CACHING BENCHMARK: {tag}")
    print(f"   Prompt Size: ~1,500 tokens | Requests: {len(QUESTIONS)} Sequential")
    print(f"=========================================================================\n")
    print(f"{'Req':<4} | {'Status':<12} | {'TTFT (ms)':<10} | {'TPOT (ms)':<10} | {'Tokens':<6} | {'Sample Output'}")
    print("-" * 85)

    ttfts = []
    tpots = []

    for i, q in enumerate(QUESTIONS):
        payload = {
            "model": "qwen-1.5b",
            "messages": [
                {"role": "system", "content": SHARED_DOCUMENT},
                {"role": "user", "content": f"{q} Answer concisely in one sentence."}
            ],
            "temperature": 0.0,
            "max_tokens": 50,
            "stream": True
        }

        t0 = time.perf_counter()
        r = requests.post("http://localhost:8000/v1/chat/completions", json=payload, stream=True)
        
        t_first = None
        output_tokens = 0
        text = ""

        for line in r.iter_lines():
            if not line:
                continue
            line_str = line.decode('utf-8')
            if line_str.startswith("data: "):
                data_str = line_str[6:].strip()
                if data_str == "[DONE]":
                    break
                try:
                    chunk = json.loads(data_str)
                    delta = chunk["choices"][0]["delta"].get("content", "")
                    if delta:
                        if t_first is None:
                            t_first = time.perf_counter()
                        output_tokens += 1
                        text += delta
                except Exception:
                    pass

        t_end = time.perf_counter()
        
        ttft_ms = (t_first - t0) * 1000 if t_first else 0
        tpot_ms = ((t_end - t_first) / max(1, (output_tokens - 1))) * 1000 if (t_first and output_tokens > 1) else 0

        status = "COLD (Miss)" if i == 0 else "WARM (Hit)"
        ttfts.append(ttft_ms)
        tpots.append(tpot_ms)

        print(f"{i+1:<4} | {status:<12} | {ttft_ms:9.1f} | {tpot_ms:9.1f} | {output_tokens:<6} | {text.strip()[:40]}...")

    cold_ttft = ttfts[0]
    warm_ttfts = ttfts[1:]
    warm_avg = statistics.mean(warm_ttfts)
    warm_median = statistics.median(warm_ttfts)
    speedup = cold_ttft / max(0.1, warm_median)
    reduction_pct = ((cold_ttft - warm_median) / cold_ttft) * 100

    print(f"\n=======================================================================")
    print(f"                           SUMMARY: {tag}")
    print(f"=======================================================================")
    print(f"  * Cold Start TTFT (Req 1 Miss)   : {cold_ttft:7.1f} ms")
    print(f"  * Warm Average TTFT (Reqs 2-10)  : {warm_avg:7.1f} ms")
    print(f"  * Warm Median TTFT (Reqs 2-10)   : {warm_median:7.1f} ms")
    print(f"  * TTFT Latency Reduction         : {reduction_pct:7.1f} %")
    print(f"  * Prefix Caching TTFT Speedup    : {speedup:7.1f} x")
    print(f"=======================================================================\n")

if __name__ == '__main__':
    label = sys.argv[1] if len(sys.argv) > 1 else "TEST"
    run_benchmark(label)
